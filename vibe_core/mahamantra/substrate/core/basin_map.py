def _compute_phoneme_attractor_table() -> Tuple[int, ...]:
    """Compute MahaAlgorithm16 attractor for each RAMA coord. Called once at import."""
    from vibe_core.mahamantra.substrate.algorithm.maha import MahaAlgorithm16

    algo = MahaAlgorithm16()
    table = []
    for coord in range(VARNAMALA_TOTAL):
        attractor, _, _ = algo.find_attractor(coord)
        table.append(attractor)
    return tuple(table)


COORD_PHONEME_ATTRACTOR: Final[Tuple[int, ...]] = _compute_phoneme_attractor_table()

# The 5 unique phoneme attractors (Mahamantra constants)
PHONEME_ATTRACTOR_SET: Final[FrozenSet[int]] = frozenset(COORD_PHONEME_ATTRACTOR)
PHONEME_ATTRACTOR_LIST: Final[Tuple[int, ...]] = tuple(sorted(PHONEME_ATTRACTOR_SET))
PHONEME_ATTRACTOR_COUNT: Final[int] = len(PHONEME_ATTRACTOR_LIST)
PHONEME_ATTRACTOR_INDEX: Final[dict] = {a: i for i, a in enumerate(PHONEME_ATTRACTOR_LIST)}


def phoneme_attractor_histogram(coords: Sequence[int]) -> Tuple[int, ...]:
    """Histogram of phoneme attractors for a coord sequence (length = PHONEME_ATTRACTOR_COUNT)."""
    hist = [0] * PHONEME_ATTRACTOR_COUNT
    for c in coords:
        a = COORD_PHONEME_ATTRACTOR[c]
        hist[PHONEME_ATTRACTOR_INDEX[a]] += 1
