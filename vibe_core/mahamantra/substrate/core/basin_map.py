def phoneme_attractor_similarity(coords_a: Sequence[int], coords_b: Sequence[int]) -> float:
    """Cosine similarity of phoneme attractor histograms. 1.0 = identical charge distribution."""
    ha = phoneme_attractor_histogram(coords_a)
    hb = phoneme_attractor_histogram(coords_b)
    dot = sum(ha[i] * hb[i] for i in range(PHONEME_ATTRACTOR_COUNT))
    mag_a = sum(v * v for v in ha) ** 0.5
    mag_b = sum(v * v for v in hb) ** 0.5
    if mag_a == 0.0 or mag_b == 0.0:
        return 0.0
    return dot / (mag_a * mag_b)


# =============================================================================
# HKR PROPORTION TABLE
# =============================================================================
# For each RAMA coord, trace through all 16 Maha Algorithm steps.
# Record how much each operation (H/K/R) changes the value.
# Normalize to (h, k, r) where h + k + r ≈ 1.0.


def _compute_hkr_table() -> Tuple[Tuple[float, float, float], ...]:
    """Compute HKR proportion for each RAMA coord. Called once at import."""
    from vibe_core.mahamantra.substrate.algorithm.maha import (
        BINARY_PATTERN,
        MAHA_16_STEPS,
        MahaSynthParams,
    )
    from vibe_core.mahamantra.protocols._seed import (
        KSETRAJNA,
        MAHA_OP_MAP,
        MAHA_SQ,
        MAHAMANTRA_NAME_HARE,
        MAHAMANTRA_NAME_KRISHNA,
        SEVEN,
        TEN,
        WORDS,
    )

    _name_to_key = {
        MAHAMANTRA_NAME_HARE: "H",
        MAHAMANTRA_NAME_KRISHNA: "K",
    }  # everything else is R

    p = MahaSynthParams(mod_space=MAHA_QUANTUM, feedback=KSETRAJNA)
    table = []

    for coord in range(VARNAMALA_TOTAL):
        value = coord % MAHA_QUANTUM
        feedback_acc = 0
        deltas = {"H": 0, "K": 0, "R": 0}

        for step in MAHA_16_STEPS:
            effective_pos = ((step.position - KSETRAJNA + p.phase_offset) % WORDS) + KSETRAJNA

            lfo = 0
            if p.lfo_enabled:
                binary_val = BINARY_PATTERN[(step.position - KSETRAJNA) % WORDS]
                phase_in_lfo = (step.position - KSETRAJNA) % p.lfo_rate
                lfo = binary_val * phase_in_lfo

            adsr_table = (p.adsr_attack, p.adsr_decay, p.adsr_sustain, p.adsr_release)
            adsr = adsr_table[step.phase.value - KSETRAJNA]

            op_key = _name_to_key.get(step.name, "R")
            op = MAHA_OP_MAP[op_key]
            mod = MAHA_QUANTUM

            mult_coeff = (SEVEN * adsr, KSETRAJNA, KSETRAJNA)[op]
            add_coeff = (lfo, TEN + effective_pos + feedback_acc, feedback_acc)[op]

            v = (value * mult_coeff + add_coeff) % mod
            squared = (v * v) % mod
            new_value = MAHA_SQ[op] * squared + (KSETRAJNA - MAHA_SQ[op]) * v

            deltas[op_key] += abs(new_value - value)
            value = new_value
            feedback_acc = (feedback_acc + value * p.feedback) % MAHA_QUANTUM

        total = deltas["H"] + deltas["K"] + deltas["R"]
        if total == 0:
            table.append((0.333, 0.333, 0.334))
        else:
            table.append(
                (
                    deltas["H"] / total,
                    deltas["K"] / total,
                    deltas["R"] / total,
                )
            )

    return tuple(table)


COORD_HKR: Final[Tuple[Tuple[float, float, float], ...]] = _compute_hkr_table()


