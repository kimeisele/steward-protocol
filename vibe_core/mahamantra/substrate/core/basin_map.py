from __future__ import annotations

from typing import Final, FrozenSet, Sequence, Tuple

from vibe_core.mahamantra.protocols._seed import MAHA_QUANTUM
from vibe_core.mahamantra.substrate.rama_grid import VARNAMALA_TOTAL

# =============================================================================
# PRECOMPUTED BASIN TABLE
# =============================================================================
# Generated by iterating MahaModularSynth("quantum").transform() until
# convergence for each RAMA coordinate (0-48).
#
# 7 unique basins: {11, 22, 38, 59, 88, 115, 122}
#
# Basin semantics (from Gita word frequency analysis):
#   11  = vayu    : opulence, devotion, consciousness
#   22  = vayu    : supreme, spiritual, knowledge, soul
#   38  = prithvi : material, mind, great, living, work
#   59  = vayu    : (rare — only 2 seeds)
#   88  = prithvi : supreme, activities, body, nature
#  115  = akasha  : result, ether, sacrifice, fruits
#  122  = vayu    : knowledge, intelligence, body, nature


def _compute_basin_table() -> Tuple[int, ...]:
    """Compute basin for each RAMA coord. Called once at import time."""
    from vibe_core.mahamantra.substrate.algorithm.maha import MahaModularSynth

    synth = MahaModularSynth(default_preset="quantum")
    table = []
    for coord in range(VARNAMALA_TOTAL):
        value = coord
        for _ in range(100):
            prev = value
            value = synth.transform(value)
            if value == prev:
                break
        table.append(value)
    return tuple(table)


COORD_BASIN: Final[Tuple[int, ...]] = _compute_basin_table()

# The 7 unique basins
BASIN_SET: Final[FrozenSet[int]] = frozenset(COORD_BASIN)
BASIN_COUNT: Final[int] = len(BASIN_SET)
BASIN_LIST: Final[Tuple[int, ...]] = tuple(sorted(BASIN_SET))

# Basin → index (for histogram operations)
BASIN_INDEX: Final[dict] = {b: i for i, b in enumerate(BASIN_LIST)}


# =============================================================================
# SIGNATURE FUNCTIONS
# =============================================================================


def basin_signature(coords: Sequence[int]) -> Tuple[int, ...]:
    """Per-coord basin signature. Pure lookup, no synth calls."""
    return tuple(COORD_BASIN[c] for c in coords)


def basin_set(coords: Sequence[int]) -> FrozenSet[int]:
    """Unique basins touched by a sequence of coords."""
    return frozenset(COORD_BASIN[c] for c in coords)


def basin_histogram(coords: Sequence[int]) -> Tuple[int, ...]:
    """
    Basin frequency histogram (length = BASIN_COUNT).
    Index i = count of coords in BASIN_LIST[i].
    Normalized to sum=1 would lose integer precision, so raw counts.
    """
    hist = [0] * BASIN_COUNT
    for c in coords:
        b = COORD_BASIN[c]
        hist[BASIN_INDEX[b]] += 1
    return tuple(hist)


def basin_jaccard(coords_a: Sequence[int], coords_b: Sequence[int]) -> float:
    """Jaccard similarity of basin sets. 1.0 = identical basins, 0.0 = disjoint."""
    a = basin_set(coords_a)
    b = basin_set(coords_b)
    union = a | b
    if not union:
        return 0.0
    return len(a & b) / len(union)


def basin_cosine(coords_a: Sequence[int], coords_b: Sequence[int]) -> float:
    """Cosine similarity of basin histograms. Captures proportion, not just overlap."""
    ha = basin_histogram(coords_a)
    hb = basin_histogram(coords_b)
    dot = sum(ha[i] * hb[i] for i in range(BASIN_COUNT))
    mag_a = sum(v * v for v in ha) ** 0.5
    mag_b = sum(v * v for v in hb) ** 0.5
    if mag_a == 0.0 or mag_b == 0.0:
        return 0.0
    return dot / (mag_a * mag_b)


# =============================================================================
# PHONEME ATTRACTOR TABLE
# =============================================================================
# For each RAMA coord, find the attractor under MahaAlgorithm16.transform().
# Only 5 unique attractors exist — the Mahamantra constants:
#   18  = GITA_CHAPTERS
