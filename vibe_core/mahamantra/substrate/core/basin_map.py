# HKR SIMILARITY FUNCTIONS
# =============================================================================


def hkr_color(coords: Sequence[int]) -> Tuple[float, float, float]:
    """Average HKR color for a sequence of coords."""
    if not coords:
        return (0.333, 0.333, 0.334)
    n = len(coords)
    h = sum(COORD_HKR[c][0] for c in coords) / n
    k = sum(COORD_HKR[c][1] for c in coords) / n
    r = sum(COORD_HKR[c][2] for c in coords) / n
    return (h, k, r)


def hkr_distance(coords_a: Sequence[int], coords_b: Sequence[int]) -> float:
    """Euclidean distance between HKR colors. 0.0 = identical."""
    a = hkr_color(coords_a)
    b = hkr_color(coords_b)
    return ((a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2 + (a[2] - b[2]) ** 2) ** 0.5


def hkr_similarity(coords_a: Sequence[int], coords_b: Sequence[int]) -> float:
    """HKR similarity. 1.0 = identical, 0.0 = maximally different."""
    d = hkr_distance(coords_a, coords_b)
    return max(0.0, 1.0 - d * 2.0)


