    def _write_if_missing(self, path: Path, content: str, result: GenerationResult) -> bool:
        """Write file if it doesn't exist."""
        if path.exists():
            result.skipped_files.append(str(path.name))
            return False

        if not self._dry_run:
            # Ensure parent directory exists
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            logger.info(f"Created: {path}")

        result.created_files[path.name] = path
        return True

    def _write_json_if_missing(self, path: Path, data: Dict, result: GenerationResult) -> bool:
        """Write JSON file if it doesn't exist."""
        content = json.dumps(data, indent=2)
        return self._write_if_missing(path, content, result)

    def _to_class_name(self, name: str) -> str:
        """Convert snake_case to PascalCase."""
        return "".join(word.title() for word in name.split("_"))

    def _get_default_templates(self) -> Path:
        """Get default templates directory."""
        return Path(__file__).parent / "templates"

    def _load_template(self, template_path: str, context: Dict) -> str:
        """Load and render a template."""
        full_path = self._templates_dir / template_path
        if full_path.exists():
            template = Template(full_path.read_text())
            return template.safe_substitute(context)
        return ""
