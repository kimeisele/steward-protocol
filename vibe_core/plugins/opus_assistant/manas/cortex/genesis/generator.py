    def __init__(
        self,
        workspace: Path,
        templates_dir: Optional[Path] = None,
        dry_run: bool = False,
    ):
        """
        Initialize generator.

        Args:
            workspace: Workspace root path
            templates_dir: Custom templates directory (optional)
            dry_run: If True, don't write files (for testing)
        """
        self._workspace = workspace
        self._templates_dir = templates_dir or self._get_default_templates()
        self._dry_run = dry_run

    def generate(self, path: Path, module_type: ModuleType) -> GenerationResult:
        """
        Generate infrastructure files for a module.

        Args:
            path: Path to the new module directory
            module_type: Type of module (from classifier)

        Returns:
            GenerationResult with details of what was created
        """
        result = GenerationResult(path=path, module_type=module_type)

        if module_type == ModuleType.UNKNOWN:
            result.errors.append("Cannot generate infrastructure for UNKNOWN type")
            return result

        generators = {
            ModuleType.PLUGIN: self._generate_plugin,
            ModuleType.ANALYZER: self._generate_analyzer,
            ModuleType.SENSE: self._generate_sense,
            ModuleType.ACTION: self._generate_action,
            ModuleType.SECTION: self._generate_section,
            ModuleType.KNOWLEDGE: self._generate_knowledge,
        }

        generator = generators.get(module_type)
        if generator:
            try:
                generator(path, result)
            except Exception as e:
                result.errors.append(f"Generation failed: {e}")
                logger.error(f"Infrastructure generation failed for {path}: {e}")
        else:
            result.skipped_files.append("No generator for this type")

        return result

