from datetime import datetime, timedelta
from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Optional

logger = logging.getLogger("MANAS.Intent")


class IntentPriority(Enum):
    """Priority levels for intents."""

    LOW = "low"  # Can wait, nice to have
    MEDIUM = "medium"  # Should do soon
    HIGH = "high"  # Important, do next
    CRITICAL = "critical"  # Do immediately (auto-execute if allowed)


class IntentRisk(Enum):
    """Risk levels for intents."""

    SAFE = "safe"  # Can auto-execute (e.g., cleanup logs)
    LOW = "low"  # Probably fine, but verify
    MEDIUM = "medium"  # Needs human approval
    HIGH = "high"  # Definitely needs human approval


@dataclass
class Intent:
    """A proactive intention generated by MANAS."""

    id: str  # Unique ID (e.g., "manas_001")
    intent_type: str  # Category (e.g., "cleanup_branches")
    title: str  # Short title for display
    description: str  # Detailed description
    reasoning: str  # Why MANAS thinks this is needed
    priority: IntentPriority = IntentPriority.MEDIUM
    risk: IntentRisk = IntentRisk.MEDIUM
    created_at: str = field(default_factory=lambda: datetime.utcnow().isoformat())
    circuit_to_execute: Optional[str] = None  # If we know which circuit to run
    params: Dict[str, Any] = field(default_factory=dict)  # Parameters for execution
    auto_executable: bool = False  # Can this run without approval?
    expires_at: Optional[str] = None  # When this intent becomes stale
    # WEAVING: Semantic links to related code/docs
    related_files: List[str] = field(default_factory=list)  # e.g., ["jnana.py:151"]
    related_docs: List[str] = field(default_factory=list)  # e.g., ["076-NO-PUSSY-MODE.md"]

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for serialization."""
        return {
            "id": self.id,
            "intent_type": self.intent_type,
            "title": self.title,
            "description": self.description,
            "reasoning": self.reasoning,
            "priority": self.priority.value,
            "risk": self.risk.value,
            "created_at": self.created_at,
            "circuit_to_execute": self.circuit_to_execute,
            "params": self.params,
            "auto_executable": self.auto_executable,
            "expires_at": self.expires_at,
            "related_files": self.related_files,
            "related_docs": self.related_docs,
        }

    def is_expired(self) -> bool:
        """Check if intent has expired."""
        if not self.expires_at:
            return False
        return datetime.utcnow().isoformat() > self.expires_at


class IntentGenerator:
    """
    Generates proactive intents by analyzing system state.

    This is the "thinking" part of MANAS - it observes and suggests.

    Analyzers:
    - Git state (stale branches, uncommitted changes)
    - Code health (TODOs, complexity)
    - Documentation drift
    - Test coverage gaps
    - Resource usage patterns
    - Contract violations (OPUS-032: The Immune System)
    """

    def __init__(self, workspace: Optional[Path] = None, memory_store: Optional[Any] = None):
        """
        Initialize intent generator.

        Args:
            workspace: Workspace root
            memory_store: Optional MemoryStore for learning
        """
        self._workspace = workspace or Path.cwd()
        self._memory = memory_store
        self._intent_counter = 0
        self._analyzers = self._register_analyzers()

        # OPUS-032: Modular class-based analyzers (the new way)
        self._modular_analyzers = self._register_modular_analyzers()

        # 🧠 SEMANTIC ENGINE (Lazy Injection)
        self._semantic_engine = None

    def inject_semantic_engine(self, engine: Any) -> None:
        """Inject the Semantic Engine for Level 2 intelligence."""
        self._semantic_engine = engine
        logger.info("🧠 IntentGenerator: Semantic Engine injected")

    def _register_analyzers(self) -> List[callable]:
        """Register all intent analyzers (legacy method-based)."""
        return [
            self._analyze_stale_branches,
            self._analyze_uncommitted_changes,
            self._analyze_stale_todos,
            self._analyze_test_health,
            self._analyze_documentation_drift,
            self._analyze_log_cleanup,
            # OPUS-032: Self-Documentation Analyzers
            self._analyze_readme_staleness,
            self._analyze_self_documentation,
            # OPUS-032: The Ouroboros Protocol
            self._analyze_capability_gaps,
        ]

    def _register_modular_analyzers(self) -> List[Any]:
        """
        Register modular class-based analyzers (OPUS-032, OPUS-077).

        These are the new-style analyzers that inherit from BaseAnalyzer.
        They provide better separation of concerns and are easier to test.
        """
        from .analyzers import CIMonitorAnalyzer, ContractAnalyzer, PratyayaAnalyzer, SemanticAnalyzer

        return [
            ContractAnalyzer(workspace=self._workspace),
            SemanticAnalyzer(workspace=self._workspace),  # 51% - The Genesis Impulse
            CIMonitorAnalyzer(workspace=self._workspace),  # OPUS-041 - VAK (The Voice)
            PratyayaAnalyzer(workspace=self._workspace),  # OPUS-077 - Self-Falsification
        ]

    async def generate_intents(self, context: Optional[Dict[str, Any]] = None) -> List[Intent]:
        """
        Generate intents based on current system state. (Async for semantic analysis)

        Args:
            context: Optional additional context (e.g., from Prakriti)

        Returns:
            List of generated intents
        """
        intents = []
        context = context or {}

        # OPUS-032: Run modular class-based analyzers FIRST (the new way)
        # These handle structured data like verification_results
        for analyzer in self._modular_analyzers:
            try:
                if not analyzer.is_enabled:
                    continue
                new_intents = analyzer.analyze(context)
                for intent in new_intents:
                    if self._should_skip_intent(intent):
                        logger.debug(f"Skipping intent {intent.intent_type} (memory/cooldown)")
                        continue
                    intents.append(intent)
            except Exception as e:
                logger.debug(f"Modular analyzer {analyzer.name} failed: {e}")

        # Legacy method-based analyzers (still useful for git/file checks)
        for analyzer in self._analyzers:
            try:
                intent = analyzer(context)
                if intent:
                    # Check memory - should we skip this?
                    if self._should_skip_intent(intent):
                        logger.debug(f"Skipping intent {intent.intent_type} (memory/cooldown)")
                        continue
                    intents.append(intent)
            except Exception as e:
                logger.debug(f"Analyzer {analyzer.__name__} failed: {e}")

        # 🧠 SEMANTIC ANALYSIS (Level 2)
        if self._semantic_engine:
            try:
                semantic_intents = await self._analyze_semantic_opportunities(context)
                intents.extend(semantic_intents)
            except Exception as e:
                logger.warning(f"🧠 Semantic analysis failed: {e}")

        # BHAKTI ↔ MEMORY: Boost intents that have proven successful ("muscle memory")
        if self._memory:
            successful = self._memory.get_successful_patterns()
            for intent in intents:
                if intent.intent_type in successful and intent.priority != IntentPriority.CRITICAL:
                    # Boost by one level - the system learns what works
                    boosted = {
                        IntentPriority.LOW: IntentPriority.MEDIUM,
                        IntentPriority.MEDIUM: IntentPriority.HIGH,
                        IntentPriority.HIGH: IntentPriority.CRITICAL,
                    }
                    intent.priority = boosted.get(intent.priority, intent.priority)
                    logger.info(f"🧠 MUSCLE MEMORY: Boosted '{intent.intent_type}' (proven success)")

        # Sort by priority
        priority_order = {
            IntentPriority.CRITICAL: 0,
            IntentPriority.HIGH: 1,
            IntentPriority.MEDIUM: 2,
            IntentPriority.LOW: 3,
        }
        intents.sort(key=lambda i: priority_order.get(i.priority, 99))

        logger.info(f"Generated {len(intents)} intents")
        return intents

    def _should_skip_intent(self, intent: Intent) -> bool:
        """Check if we should skip this intent based on memory."""
        if not self._memory:
            return False

        # Skip if in cooldown after failure
        if self._memory.is_in_cooldown(intent.intent_type):
            return True

        # Skip if recently rejected by user
        if self._memory.was_recently_rejected(intent.intent_type):
            return True

        return False

    def _next_intent_id(self) -> str:
        """Generate next intent ID."""
        self._intent_counter += 1
        return f"manas_{self._intent_counter:04d}"

