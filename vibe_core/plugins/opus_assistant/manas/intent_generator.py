    def _analyze_documentation_drift(self, context: Dict[str, Any]) -> Optional[Intent]:
        """
        Detect documentation that may be out of sync with code.

        Risk: LOW (just awareness)
        """
        # Check OPUS verification score from context
        verification = context.get("verification", {})
        trust_score = verification.get("trust_score", 100)

        if trust_score < 80:
            failures = verification.get("failures", [])
            return Intent(
                id=self._next_intent_id(),
                intent_type="fix_documentation_drift",
                title=f"Fix documentation drift (trust: {trust_score}%)",
                description=f"Documentation verification shows {trust_score}% trust score with {len(failures)} issues.",
                reasoning="Documentation drift means the code and docs are out of sync. This causes confusion and onboarding friction.",
                priority=IntentPriority.MEDIUM if trust_score < 70 else IntentPriority.LOW,
                risk=IntentRisk.LOW,
                circuit_to_execute="OPUS_AUTO_HEAL",
                params={"trust_score": trust_score, "failure_count": len(failures)},
                auto_executable=False,
            )

        return None

    def _analyze_log_cleanup(self, context: Dict[str, Any]) -> Optional[Intent]:
        """
        Check if log files need cleanup.

        Risk: SAFE (just deleting old logs)
        """
        try:
            log_dir = self._workspace / ".opus_state" / "logs"
            if not log_dir.exists():
                return None

            # Count log files older than 7 days
            cutoff = datetime.utcnow() - timedelta(days=7)
            old_logs = []

            for log_file in log_dir.glob("*.log"):
                mtime = datetime.fromtimestamp(log_file.stat().st_mtime)
                if mtime < cutoff:
                    old_logs.append(log_file.name)

            if len(old_logs) >= 5:
                return Intent(
                    id=self._next_intent_id(),
                    intent_type="cleanup_old_logs",
                    title=f"Clean up {len(old_logs)} old log files",
                    description=f"Found {len(old_logs)} log files older than 7 days in .opus_state/logs/",
                    reasoning="Old log files consume disk space and are rarely needed after a week.",
                    priority=IntentPriority.LOW,
                    risk=IntentRisk.SAFE,  # Safe to auto-execute
                    params={"log_files": old_logs},
                    auto_executable=True,  # Can run without approval!
                    expires_at=(datetime.utcnow() + timedelta(days=3)).isoformat(),
                )

        except Exception as e:
            logger.debug(f"Log cleanup analysis failed: {e}")

        return None

